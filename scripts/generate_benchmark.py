def generate_benchmark_dataset(
    output_dir: str = "data/benchmarks/salb3pm-97", seed: int = 42
) -> list[dict[str, Any]]:
    """
    Generate all 97 benchmark instances with w_i ~ U(5, 50).
    """
    os.makedirs(output_dir, exist_ok=True)
    rng = random.Random(seed)

    all_instances = []
    total_count = 0

    for family_name, fam_data in BENCHMARK_FAMILIES.items():
        n = fam_data["num_tasks"]
        t = fam_data["processing_times"]
        p = fam_data["precedences"]

        # Generate power consumptions w_i ~ U(5, 50) for tasks 1..n
        w = [rng.randint(5, 50) for _ in range(n)]

        for inst_info in fam_data["instances"]:
            inst_id = inst_info["id"]
            c = inst_info["c"]
            m = inst_info["m"]

            instance_dict = {
                "id": inst_id,
                "name": inst_id,
                "family": family_name,
                "cycle_time": c,
                "stations": m,
                "num_stations": m,
                "num_tasks": n,
                "tasks": [{"id": i + 1, "duration": t[i], "power": w[i]} for i in range(n)],
                "precedence": [list(arc) for arc in p],
                "processing_times": t,
                "power_consumptions": w,
                "precedences": [list(arc) for arc in p],
                "lower_bound": max(w),
                "upper_bound": sum(sorted(w, reverse=True)[:m]),
                "dataset_version": "salb3pm-ictai2024-v1",
            }

            file_path = os.path.join(output_dir, f"{inst_id}.json")
            with open(file_path, "w", encoding="utf-8") as f:
                json.dump(instance_dict, f, indent=2)

            all_instances.append(instance_dict)
            total_count += 1

    # Save manifest
    manifest_path = os.path.join(output_dir, "manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                "dataset_name": "SALB3PM Benchmark (ICTAI 2024)",
                "total_instances": total_count,
                "seed": seed,
                "families": list(BENCHMARK_FAMILIES.keys()),
                "instances": [inst["id"] for inst in all_instances],
            },
            f,
            indent=2,
        )

    print(f"Generated {total_count} benchmark instances into '{output_dir}'.")
    return all_instances


if __name__ == "__main__":
    generate_benchmark_dataset()
